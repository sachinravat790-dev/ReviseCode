let isRendering = false;

function renderLocalIcons(root = document) {
  const targetRoot = root && typeof root.querySelectorAll === 'function' ? root : document;
  const iconElements = targetRoot.querySelectorAll('i[data-lucide]');
  iconElements.forEach(el => {
    const iconName = el.getAttribute('data-lucide');
    const pathData = ICONS_SVG_MAP[iconName];
    if (pathData) {
      const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
      svg.setAttribute('viewBox', '0 0 24 24');
      svg.setAttribute('width', '24');
      svg.setAttribute('height', '24');
      svg.setAttribute('fill', 'none');
      svg.setAttribute('stroke', 'currentColor');
      svg.setAttribute('stroke-width', '2');
      svg.setAttribute('stroke-linecap', 'round');
      svg.setAttribute('stroke-linejoin', 'round');
      svg.className.baseVal = el.className || 'lucide-icon';
      svg.innerHTML = pathData;

      if (el.getAttribute('style')) {
        svg.style.cssText = el.getAttribute('style');
      }

      el.replaceWith(svg);
    }
  });
}

export function renderIcons(root = document) {
  if (isRendering) return;
  isRendering = true;

  try {
    // If native Lucide library is present on window and not our custom fallback, let it run
    if (typeof window !== 'undefined' && window.lucide && typeof window.lucide.createIcons === 'function' && !window.lucide.__isCustom) {
      try {
        window.lucide.createIcons();
      } catch (_) {}
    }

    // Also replace any unprocessed or offline <i data-lucide="..."> tags
    renderLocalIcons(root);
  } finally {
    isRendering = false;
  }
}

// Automatically provide Lucide fallback if not loaded from CDN
if (typeof window !== 'undefined' && !window.lucide) {
  window.lucide = {
    __isCustom: true,
    createIcons: (options) => renderLocalIcons(options?.root || document)
  };
}

if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    renderIcons();
  });
}
